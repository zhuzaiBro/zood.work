DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM field_collections f JOIN public.interview_collections c
      ON c.title = f.title AND c.id <> f.id
  ) OR EXISTS (
    SELECT 1 FROM field_questions f JOIN public.interview_question q
      ON (q.title = f.title AND q.id <> f.id)
        OR (q.id = f.id AND q.collection_id IS DISTINCT FROM f.collection_id)
  ) THEN
    RAISE EXCEPTION 'Existing editorial content conflicts with this import';
  END IF;
END $$;

INSERT INTO public.interview_collections (id, title, description, sort, icon)
SELECT id, title, description, sort, icon FROM field_collections
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.interview_collection_roles (collection_id, role_slug)
SELECT f.id, f.role_slug FROM field_collections f
WHERE NOT EXISTS (
  SELECT 1 FROM public.interview_collection_roles r WHERE r.collection_id = f.id AND r.role_slug = f.role_slug
)
ON CONFLICT (role_slug, collection_id) DO NOTHING;

INSERT INTO public.interview_question (id, collection_id, sort, difficulty, title, content, is_vip, vip_level_required)
SELECT id, collection_id, sort, difficulty, title, content, false, 0 FROM field_questions
ON CONFLICT (id) DO NOTHING;

